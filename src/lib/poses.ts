export const FALLBACK_POSE = 'plank'

export function getPose(key: string): Pose | undefined {
  return POSES[key]
}

/** Poses that do not exist fall back gracefully so the UI never breaks. */
export function resolvePoses(keys: string[] | undefined): Pose[] {
  if (!keys?.length) return []
  const resolved = keys.map((key) => POSES[key]).filter((pose): pose is Pose => Boolean(pose))
  if (!resolved.length) {
    const fallback = POSES[FALLBACK_POSE]
    return fallback ? [fallback] : []
  }
  return resolved
}

export type InterpolatedPose = Omit<Pose, 'arm2' | 'leg2'> & {
  arm2?: { elbow: Joint; hand: Joint }
  leg2?: { knee: Joint; foot: Joint }
}

const lerp = (a: number, b: number, t: number) => a + (b - a) * t
const lerpJoint = (a: Joint, b: Joint, t: number): Joint => [
  lerp(a[0], b[0], t),
  lerp(a[1], b[1], t),
]

/** Smoothstep easing keeps the motion from looking mechanical. */
const ease = (t: number) => t * t * (3 - 2 * t)

export function interpolatePose(from: Pose, to: Pose, rawT: number): InterpolatedPose {
  const t = ease(Math.max(0, Math.min(1, rawT)))
  const mix = (a: Joint, b: Joint) => lerpJoint(a, b, t)

  const arm2 =
    from.arm2 && to.arm2
      ? { elbow: mix(from.arm2.elbow, to.arm2.elbow), hand: mix(from.arm2.hand, to.arm2.hand) }
      : from.arm2 && to.arm2 === undefined
        ? undefined
        : to.arm2 && from.arm2 === undefined
          ? { elbow: to.arm2.elbow, hand: to.arm2.hand }
          : undefined

  const leg2 =
    from.leg2 && to.leg2
      ? { knee: mix(from.leg2.knee, to.leg2.knee), foot: mix(from.leg2.foot, to.leg2.foot) }
      : from.leg2 && to.leg2 === undefined
        ? undefined
        : to.leg2 && from.leg2 === undefined
          ? { knee: to.leg2.knee, foot: to.leg2.foot }
          : undefined

  return {
    scene: to.scene,
    head: mix(from.head, to.head),
    neck: mix(from.neck, to.neck),
    hip: mix(from.hip, to.hip),
    elbow: mix(from.elbow, to.elbow),
    hand: mix(from.hand, to.hand),
    knee: mix(from.knee, to.knee),
    foot: mix(from.foot, to.foot),
    arm2,
    leg2,
  }
}
