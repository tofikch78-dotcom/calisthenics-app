/**
 * Pose library for the exercise illustrations.
 *
 * Every pose is a side-on stick figure expressed as joint coordinates inside a
 * 200×200 viewBox. The renderer interpolates between poses to produce the
 * looping "animation" on each exercise card.
 */

export type Joint = readonly [number, number]

export type Scene =
  | 'floor'
  | 'wall'
  | 'pull-bar'
  | 'wall-pull-bar'
  | 'low-bar'
  | 'dip-bars'
  | 'rings'
  | 'bench'
  | 'box'
  | 'chair'
  | 'pole'

export interface Pose {
  scene: Scene
  head: Joint
  neck: Joint
  hip: Joint
  elbow: Joint
  hand: Joint
  knee: Joint
  foot: Joint
  /** Second limb, drawn faded — used for split stances and two-arm holds. */
  arm2?: { elbow: Joint; hand: Joint }
  leg2?: { knee: Joint; foot: Joint }
}

